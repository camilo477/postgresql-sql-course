-- Ejercicio 1 — Diseño práctico
-- Necesitamos crear una tabla llamada lab_customers para registrar clientes de una aplicación financiera.

-- Usaremos una tabla de laboratorio separada para no modificar las tablas de los bloques anteriores.

-- Sus requisitos son:
-- Columna	Requisito
-- id	Entero, identificador automático y Primary Key
-- full_name	Texto obligatorio
-- email	Texto obligatorio y único
-- phone	Texto opcional
-- registered_at	Fecha y hora considerando zonas horarias, obligatoria

-- Tu tarea: escribe la sentencia CREATE TABLE completa.

-- Debes utilizar IDENTITY, PRIMARY KEY, NOT NULL y UNIQUE donde corresponda.

-- No utilizarás CHECK, DEFAULT ni FOREIGN KEY todavía.

-- Después de escribirla, ejecútala en PostgreSQL e inspecciona su estructura con:
-- \d lab_customers

CREATE TABLE lab_customers(
    id INTEGER generated by DEFAULT as identity primary key,
    full_name text not null,
    email text not null UNIQUE,
    phone text,
    registered_at TIMESTAMPTZ not null
);

-- Ejercicio 1 — Diseña una tabla
-- En tu base finance_practice, crea una tabla llamada lab_savings_goals.

-- Debe cumplir estos requisitos:
-- Columna	Requisito
-- id	INTEGER, IDENTITY, PRIMARY KEY
-- name	Texto obligatorio
-- target_amount	NUMERIC(12,2), obligatorio y estrictamente mayor que cero
-- is_active	Booleano, obligatorio, TRUE por defecto
-- created_at	TIMESTAMPTZ, obligatorio, fecha/hora actual por defecto

-- Para la fecha y hora actual puedes utilizar la función NOW().

-- Tú debes escribir el CREATE TABLE completo.

create table lab_savings_goals(
    id integer generated by default as identity primary key,
    name text not null,
    target_amount numeric(12,2) not null check (target_amount > 0),
    is_active bool not null default TRUE,
    created_at timestamptz not null default now()
);