-- Ahora debes crear una tabla llamada lab_wallets.

-- Requisitos:
-- Columna	Restricción
-- id	INTEGER, IDENTITY, PRIMARY KEY
-- name	TEXT, obligatorio
-- customer_id	INTEGER, obligatorio y FOREIGN KEY hacia lab_customers.id
-- balance	NUMERIC(12,2), obligatorio y mayor o igual a cero

-- Tú escribes la sentencia CREATE TABLE.

-- Después ejecútala en PostgreSQL e inspecciona su estructura con \d lab_wallets.

create table lab_wallets(
    id INTEGER generated by default as identity primary key,
    name text not null,
    customer_id integer not null references lab_customers(id),
    balance numeric(12,2) not null check(balance >0)
);


