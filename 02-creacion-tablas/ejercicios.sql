Ejercicio 3 — Tu primera tabla financiera
Ahora sí vamos a trabajar con nuestra base de datos.
Contexto
Estamos desarrollando una pequeña base financiera de práctica.
Necesitamos una tabla para almacenar categorías de transacciones.
Por ejemplo:
Alimentación
Transporte
Salario
Entretenimiento

La tabla se llamará:
categories
Requisitos
Debes crear una tabla con las siguientes columnas:
Columna	Información que almacena
id	Identificador único de la categoría
name	Nombre de la categoría
is_active	Indica si la categoría está activa
created_on	Fecha en que se creó la categoría


Condiciones
1. Utiliza CREATE TABLE.
2. Selecciona el tipo de dato adecuado para cada columna.
3. Define una Primary Key.
4. Utiliza nombres de columnas en snake_case.
5. Ejecuta la consulta desde psql, conectado a finance_practice.
6. Comprueba que la tabla existe.
7. Inspecciona su estructura.

CREATE TABLE categories(
    id INTEGER PRIMARY KEY,
    name TEXT,
    is_active BOOL,
    created_on DATE
);

