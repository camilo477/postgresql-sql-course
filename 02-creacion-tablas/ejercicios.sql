Ejercicio 5 — Diseño de una tabla financiera
Ahora quiero que construyas una tabla un poco más completa.
Contexto
Estamos desarrollando una base de datos que permitirá almacenar cuentas financieras.
Por ejemplo:
Nequi
Bancolombia
Davivienda
Efectivo

Necesitamos crear una tabla llamada accounts.
Requisitos
Columna	Requisito
id	Identificador entero y Primary Key
name	Nombre de la cuenta
balance	Cantidad monetaria con máximo 12 dígitos totales y 2 decimales
account_type	Tipo de cuenta, máximo 30 caracteres
is_active	Indica si está activa
created_at	Fecha y hora de creación considerando zonas horarias


Tu tarea: escribe la sentencia CREATE TABLE accounts utilizando los tipos correctos.

CREATE TABLE accounts(
    id INTEGER PRIMARY KEY,
    name TEXT,
    balance NUMERIC(12, 2),
    account_type VARCHAR(30),
    is_active BOOL,
    created_at TIMESTAMPTZ
);


SQL práctico
Diseña una tabla llamada payment_methods.
Debe tener:
Columna	Requisito
id	INTEGER, Primary Key y generación automática mediante IDENTITY
name	Texto
is_active	Booleano
created_at	Fecha y hora considerando zonas horarias


Tú escribes la sentencia CREATE TABLE.
Utiliza GENERATED BY DEFAULT AS IDENTITY.

CREATE TABLE payment_methods(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text,
    is_active BOOL,
    created_at TIMESTAMPTZ
);

