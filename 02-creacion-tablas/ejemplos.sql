CREATE TABLE books (
    id INTEGER PRIMARY KEY,
    title TEXT,
    published_at DATE
);

CREATE TABLE products(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    price NUMERIC(12, 2),
    stock INTEGER,
    is_active BOOL,
    created_at TIMESTAMPTZ
);


CREATE TABLE employees(
    id INTEGER PRIMARY KEY,
    name TEXT,
    salary NUMERIC(10,2),
    is_active BOOLEAN
);

CREATE TABLE invoices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total NUMERIC,
    created_at TIMESTAMPTZ
);