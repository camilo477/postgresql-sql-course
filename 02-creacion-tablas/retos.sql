Bloque 2 — Mini reto práctico
Nombre: Diseño de una pequeña base de datos financiera.
Dificultad: Intermedia respecto a lo que hemos estudiado.
Objetivo: Demostrar que puedes crear tablas correctamente sin que yo te indique los tipos de datos ni escriba las sentencias SQL.
Trabajaremos dentro de nuestra base de datos:
finance_practice
Contexto
Estamos desarrollando una aplicación para gestionar finanzas personales.
Necesitamos almacenar información relacionada con:
- Metas de ahorro.
- Instituciones financieras.
Deberás diseñar dos tablas.
Reto 1 — Tabla savings_goals
Queremos almacenar las metas de ahorro de una persona.
Ejemplo:
Quiero ahorrar $5.000.000 para comprar una motocicleta antes del 30 de junio de 2027.

Tu tabla debe permitir almacenar:
Información	Requisito
Identificador	Único y generado automáticamente
Nombre de la meta	Texto
Cantidad objetivo	Máximo 12 dígitos totales y 2 decimales
Fecha límite	Solamente fecha
Estado	Indica si la meta está activa
Fecha de creación	Fecha y hora considerando zonas horarias


Tu responsabilidad:
1. Elegir los nombres de las columnas.
2. Elegir los tipos de datos.
3. Definir la Primary Key.
4. Implementar generación automática con IDENTITY.
5. Escribir la sentencia CREATE TABLE.
No necesitas utilizar todavía NOT NULL, DEFAULT ni Foreign Keys.

Reto 2 — Tabla financial_institutions
Ahora necesitamos almacenar instituciones financieras.
Por ejemplo:
Bancolombia
Davivienda
Nu
Banco de Bogotá

La tabla debe almacenar:
Información	Requisito
Identificador	Único y generado automáticamente
Nombre de la institución	Máximo 80 caracteres
Código del país	Exactamente 2 caracteres como requisito conceptual
Estado	Activa o inactiva
Fecha de registro	Fecha y hora considerando zonas horarias


Importante: todavía no hemos estudiado las restricciones necesarias para exigir exactamente dos caracteres. Por ahora basta con utilizar un tipo que permita almacenar hasta dos caracteres.

CREATE TABLE savings_goals(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    amount NUMERIC(12,2),
    deadline DATE,
    is_active BOOL,
    create_at TIMESTAMPTZ
);

CREATE TABLE financial_institutions(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80),
    country_code VARCHAR(2),
    is_active BOOL,
    create_at TIMESTAMPTZ
);


