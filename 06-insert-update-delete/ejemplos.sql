Ejemplo práctico
Supongamos que tenemos esta estructura

CREATE TABLE payment_methods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    is_active BOOLEAN
);

Podemos insertar un registro:
INSERT INTO payment_methods (name, is_active)
VALUES ('Transferencia', TRUE);

¿Por qué no proporcionamos el ID?
Porque tenemos:
id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY

