-- Ejercicio 7 — COUNT + múltiples JOIN
-- Escribe una consulta que cuente todas las transacciones pertenecientes a Carlos, considerando todas sus cuentas financieras.

-- Requisitos:
-- - Utilizar customers, wallets y transactions.
-- - Utilizar dos INNER JOIN.
-- - Filtrar mediante customers.id = 1.
-- - Devolver una columna llamada total_transactions.
-- Ejercicio 8 — SUM + múltiples JOIN
-- Ahora queremos conocer la suma de los importes de las transacciones de Carlos que sean estrictamente mayores que 50000.

-- Requisitos:
-- - Utilizar las mismas tres tablas.
-- - Utilizar dos INNER JOIN.
-- - Filtrar por el identificador de Carlos.
-- - Incluir solamente transacciones con amount > 50000.
-- - Devolver una columna llamada total_amount.
--7
select count(*) as total_transactions
from transactions as t
inner join wallets as w
on t.wallet_id = w.id
inner join customers as c
on w.customer_id = c.id
where c.id = 1;

--8
select sum(amount) as total_amount
from transactions as t
inner join wallets as w
on t.wallet_id = w.id
inner join customers as c
on w.customer_id = c.id
where c.id = 1 and amount >50000;