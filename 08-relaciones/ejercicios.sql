-- lab_savings_goals
-- -----------------
-- id (PK)


-- Debes crear una tabla con:
-- Columna	Requisito
-- customer_id	INTEGER, FK hacia lab_customers.id
-- goal_id	INTEGER, FK hacia lab_savings_goals.id

-- Además:
-- 1. Ambas columnas deben ser obligatorias.
-- 2. La combinación (customer_id, goal_id) debe ser la Primary Key.
-- 3. No necesitas crear una columna id independiente.
-- Escribe tú mismo el CREATE TABLE completo.

create table lab_goal_participants(
    customer_id integer not null references lab_customers(id),
    goal_id integer not null references lab_savings_goals(id),
    primary key (customer_id, goal_id)
);

