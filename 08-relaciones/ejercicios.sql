-- Ejercicio 2 — SQL práctico
-- Necesitamos crear una tabla lab_customer_profiles.

-- Ya tenemos nuestra tabla lab_customers en finance_practice.

-- Los requisitos de lab_customer_profiles son:
-- Columna	Requisito
-- id	INTEGER, IDENTITY, PRIMARY KEY
-- customer_id	INTEGER, obligatorio, FK a lab_customers.id y único
-- preferred_currency	VARCHAR(3), obligatorio
-- is_active	BOOLEAN, obligatorio, TRUE por defecto

-- Tu tarea: escribe la sentencia CREATE TABLE completa.

create table lab_customer_profiles(
    id integer generated by DEFAULT as identity primary key,
    customer_id integer not null unique references lab_customers(id),
    preferred_currency varchar(3) not null,
    is_active bool not null DEFAULT TRUE
);

